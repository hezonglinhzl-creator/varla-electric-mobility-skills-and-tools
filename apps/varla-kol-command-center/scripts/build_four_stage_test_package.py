def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _text_nodes(paragraph) -> list:
    return list(paragraph._p.iter(qn("w:t")))


def _replace_span(paragraph, start: int, end: int, replacement: str) -> None:
    nodes = _text_nodes(paragraph)
    if start == end:
        if replacement:
            paragraph.add_run(replacement)
        return
    positions: list[tuple[object, int, int]] = []
    cursor = 0
    for node in nodes:
        value = node.text or ""
        positions.append((node, cursor, cursor + len(value)))
        cursor += len(value)
    touched = [
        (node, node_start, node_end)
        for node, node_start, node_end in positions
        if node_end > start and node_start < end
    ]
    if not touched:
        raise RuntimeError("Cannot map replacement span to DOCX text nodes")
    first, first_start, _ = touched[0]
    last, last_start, _ = touched[-1]
    first_text = first.text or ""
    last_text = last.text or ""
    prefix = first_text[: max(0, start - first_start)]
    suffix = last_text[max(0, end - last_start) :]
    if first is last:
        first.text = prefix + replacement + suffix
        return
    first.text = prefix + replacement
    for node, _, _ in touched[1:-1]:
        node.text = ""
    last.text = suffix


def _update_paragraph(paragraph) -> None:
    text = "".join((node.text or "") for node in _text_nodes(paragraph))
    if "@xxxxx_" in text:
        for match in reversed(list(re.finditer(re.escape("@xxxxx_"), text, re.IGNORECASE))):
            _replace_span(paragraph, match.start(), match.end(), "")
        text = "".join((node.text or "") for node in _text_nodes(paragraph))
    deliverables = re.match(r"^(\s*Deliverables\s*:\s*)(.*)$", text, re.IGNORECASE)
    if deliverables:
        replacement = DELIVERABLES.split(":", 1)[1].lstrip()
        _replace_span(paragraph, deliverables.start(2), deliverables.end(2), replacement)
        return
    posted_videos = re.match(
        r"^\s*2\s+videos\s+will\s+be\s+posted\b.*$",
        text,
        re.IGNORECASE,
    )
    if posted_videos:
        _replace_span(paragraph, 0, len(text), REAL_TEMPLATE_DELIVERABLES)
        return
    if all(label in text for label in ("Full Name:", "Shipping Address:", "Phone Number:")):
        preceding = ""
        for run in paragraph.runs:
            if run.text == ":":
                label = preceding.strip().lower()
                if label in {"full name", "shipping address", "phone number"}:
                    run.add_text(" To be confirmed")
            if run.text and run.text != "\n":
                preceding = run.text
        return
    for label, value in FIELD_VALUES.items():
        match = re.match(
            rf"^(\s*{re.escape(label)}\s*:\s*)(.*)$", text, re.IGNORECASE
        )
        if match:
            _replace_span(paragraph, match.start(2), match.end(2), value)
            return


def _update_paragraphs(paragraphs) -> None:
    for paragraph in paragraphs:
        _update_paragraph(paragraph)


def _update_tables(tables) -> None:
    for table in tables:
        for row in table.rows:
            cells = row.cells
            for index, cell in enumerate(cells):
                label = cell.text.strip().rstrip(":").strip().lower()
                if label in FIELD_VALUES and index + 1 < len(cells):
                    target = cells[index + 1]
                    first = target.paragraphs[0]
                    current = "".join(
                        (node.text or "") for node in _text_nodes(first)
                    )
                    _replace_span(first, 0, len(current), FIELD_VALUES[label])
                    for paragraph in target.paragraphs[1:]:
                        current = "".join(
                            (node.text or "") for node in _text_nodes(paragraph)
                        )
                        _replace_span(paragraph, 0, len(current), "")
                _update_paragraphs(cell.paragraphs)
                _update_tables(cell.tables)


def _edit_contract(source: Path, destination: Path, run_id: str) -> None:
    document = Document(source)
    _update_paragraphs(document.paragraphs)
    _update_tables(document.tables)
    for section in document.sections:
        for container in (section.header, section.footer):
            _update_paragraphs(container.paragraphs)
            _update_tables(container.tables)

    warning = document.paragraphs[0].insert_paragraph_before(WARNING)
    warning.alignment = WD_ALIGN_PARAGRAPH.CENTER
    warning_run = warning.runs[0]
    warning_run.bold = True
    warning_run.font.size = Pt(16)
    warning_run.font.color.rgb = RGBColor(192, 0, 0)
    metadata = document.paragraphs[1].insert_paragraph_before(
        f"Test run: {run_id} | Unconfirmed fields: To be confirmed"
    )
    metadata.alignment = WD_ALIGN_PARAGRAPH.CENTER
    if metadata.runs:
        metadata.runs[0].bold = True
    details = document.paragraphs[2].insert_paragraph_before()
    detail_lines = (
        f"Test creator: KOL Test Creator | Test email: {RECIPIENT}",
        "Product model: To be confirmed | Payment/commission: To be confirmed | "
        "Discount code: To be confirmed | Impact ID: To be confirmed",
        "Shipping full name: To be confirmed | Shipping address: To be confirmed | "
        "Phone number: To be confirmed",
        DELIVERABLES,
    )
    for index, line in enumerate(detail_lines):
        run = details.add_run(line)
        if index == 0:
            run.bold = True
        if index + 1 < len(detail_lines):
            run.add_break()

    document.core_properties.author = "Varla Marketing Team"
    document.core_properties.last_modified_by = "Varla Marketing Team"
    for property_name in (
        "title",
        "subject",
        "keywords",
        "category",
        "comments",
        "content_status",
        "identifier",
        "language",
        "version",
    ):
        if hasattr(document.core_properties, property_name):
            setattr(document.core_properties, property_name, "")
    document.save(destination)


def _xml_surfaces(path: Path) -> list[str]:
    surfaces: list[str] = []
    with zipfile.ZipFile(path) as archive:
        for name in archive.namelist():
            lowered_name = name.lower()
            if not (lowered_name.endswith(".xml") or lowered_name.endswith(".rels")):
                continue
            payload = archive.read(name)
            raw = payload.decode("utf-8", errors="ignore")
            surfaces.append(raw)
            try:
                root = ElementTree.fromstring(payload)
            except ElementTree.ParseError:
                continue
            for element in root.iter():
                if element.tag.rsplit("}", 1)[-1] == "p":
                    surfaces.append("".join(element.itertext()))
            surfaces.append("".join(root.itertext()))
            surfaces.extend(str(value) for element in root.iter() for value in element.attrib.values())
    return surfaces


